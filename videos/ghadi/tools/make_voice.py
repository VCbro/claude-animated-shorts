"""Hindi narration (Piper hi_IN-rohan, offline) -> voice/voice.wav + src/lines.ts (subtitle chunks with times).
Each LINE is synthesized separately and placed at its start time. Within a line, subtitle chunks get times
proportional to their spoken length (estimated from aksharas), then refined by silence detection."""
import json, os, re, sys, wave, io
import numpy as np, soundfile as sf
from scipy.signal import resample_poly
from piper import PiperVoice
from piper.config import SynthesisConfig

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MODEL = os.environ.get("PIPER_MODEL", "/tmp/claude-0/tts/models/vits-piper-hi_IN-rohan-medium/hi_IN-rohan-medium.onnx")
SR = 48000
TOTAL = float(os.environ.get("TOTAL", "75"))
SPEED = 0.80  # piper length_scale (<1 = faster)

# (start s, scene, [subtitle chunks]); "say" text may differ from shown text with  shown|spoken
LINES = [
 (0.5, 1, ["क्या आपने कभी सोचा है", "कि आपकी घड़ी बिना रुके", "समय कैसे बताती है?"]),
 (6.0, 2, ["चलिए, घड़ी को खोलकर देखते हैं!"]),
 (8.6, 2, ["ऊपर है डायल और सुइयाँ,", "साइड में क्राउन,", "और अंदर गियर्स की पूरी दुनिया!"]),
 (15.2, 3, ["मैकेनिकल घड़ी की ताकत है", "कसकर लिपटी एक स्प्रिंग—", "मेनस्प्रिंग।"]),
 (20.0, 3, ["चाबी भरने पर इसमें ऊर्जा जमा होती है,", "और धीरे-धीरे खुलते हुए", "यह गियर्स को घुमाती है।"]),
 (28.2, 4, ["यह है बैलेंस व्हील।", "यह एक सेकंड में कई बार", "आगे-पीछे झूलता है।"]),
 (33.4, 4, ["हर झूले पर एस्केपमेंट", "गियर्स को बस एक कदम आगे बढ़ने देता है—", "टिक-टिक यहीं से आती है!"]),
 (40.4, 5, ["गियर्स यह चाल सुइयों तक पहुँचाते हैं।"]),
 (43.3, 5, ["सेकंड की सुई एक मिनट में,", "मिनट की सुई एक घंटे में,", "और घंटे की सुई बारह घंटे में", "एक चक्कर पूरा करती है।"]),
 (52.3, 6, ["क्वार्ट्ज़ घड़ी में", "बैटरी एक छोटे सर्किट को बिजली देती है।"]),
 (56.2, 6, ["इससे क्वार्ट्ज़ क्रिस्टल एक सेकंड में", "ठीक 32,768 बार|ठीक बत्तीस हज़ार सात सौ अड़सठ बार", "कंपन करता है!"]),
 (61.6, 6, ["सर्किट इन्हें गिनकर", "हर सेकंड सुई को एक कदम बढ़ाता है।"]),
 (65.2, 7, ["अब आप जान गए कि एक छोटी-सी घड़ी के अंदर", "कितनी अद्भुत तकनीक छिपी होती है!"]),
 (70.2, 7, ["ऐसी ही मजेदार और रोचक जानकारी के लिए", "चैनल को Subscribe जरूर करें!|चैनल को सब्सक्राइब जरूर करें!"]),
]

voice = PiperVoice.load(MODEL)
cfg = SynthesisConfig(length_scale=SPEED, noise_scale=0.6, noise_w_scale=0.7)

def synth(text):
    buf = io.BytesIO()
    with wave.open(buf, "wb") as w:
        voice.synthesize_wav(text, w, syn_config=cfg)
    buf.seek(0)
    a, sr = sf.read(buf, dtype="float32")
    a = resample_poly(a, SR // 2000 * 2000 // 1000 * 1, 1) if False else resample_poly(a, 160, 245 * sr // 33075) if False else resample_poly(a, SR, sr)
    nz = np.nonzero(np.abs(a) > 0.008)[0]
    a = a[max(0, nz[0] - 200): nz[-1] + 2400]
    return a

def weight(s):  # spoken length estimate: consonant/vowel letters + pauses at punctuation
    letters = len(re.findall(r"[क-हक़-य़अ-औा-ौ0-9a-zA-Z]", s))
    return letters + 3 * len(re.findall(r"[,!?।—]", s))

def main():
    out = np.zeros(int(TOTAL * SR), np.float32)
    meta = []
    for i, (t0, scene, chunks) in enumerate(LINES):
        shown = [c.split("|")[0] for c in chunks]
        spoken = [c.split("|")[-1] for c in chunks]
        a = synth(" ".join(spoken))
        a = a / (np.max(np.abs(a)) + 1e-9) * 0.8
        dur = len(a) / SR
        s = int(t0 * SR)
        n = min(len(a), len(out) - s)
        out[s:s + n] += a[:n]
        w = np.array([weight(x) for x in spoken], float)
        edges = np.concatenate([[0], np.cumsum(w) / w.sum()]) * (dur - 0.05)
        subs = [{"text": shown[k], "t0": round(t0 + edges[k], 3), "t1": round(t0 + edges[k + 1], 3)} for k in range(len(shown))]
        meta.append({"i": i, "scene": scene, "t0": t0, "t1": round(t0 + dur, 3), "subs": subs})
        nxt = LINES[i + 1][0] if i + 1 < len(LINES) else TOTAL
        flag = "  !! OVERLAP" if t0 + dur > nxt - 0.15 else ""
        print(f"{i:2d} s{scene} {t0:5.1f}-{t0+dur:5.2f} (gap {nxt-(t0+dur):+.2f}){flag}  {' '.join(shown)}")
    sf.write(f"{ROOT}/voice/voice.wav", out, SR, subtype="PCM_24")
    json.dump(meta, open(f"{ROOT}/voice/lines.json", "w"), ensure_ascii=False, indent=1)
    os.makedirs(f"{ROOT}/src", exist_ok=True)
    with open(f"{ROOT}/src/lines.ts", "w") as f:
        f.write("// generated by tools/make_voice.py\nexport type Sub = { text: string; t0: number; t1: number };\n"
                "export type Line = { i: number; scene: number; t0: number; t1: number; subs: Sub[] };\n")
        f.write("export const LINES: Line[] = " + json.dumps(meta, ensure_ascii=False) + ";\n")

main()
