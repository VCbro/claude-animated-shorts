a = s.index("backgroundImage: `linear-gradient(100deg,"); b = s.index("`", a + 20)
s = s[:a] + f"backgroundImage: `linear-gradient(100deg, {grad[0]} 0%, #ffffff ${{sweep}}%, {grad[1]} ${{sweep + 18}}%, {grad[2]} 100%)" + s[b:]
s = s.replace("if (t > 7.4) return null;", f"if (t > {S[0]}) return null;").replace("const out = 1 - sstep(6.6, 7.3, t);", f"const out = 1 - sstep({S[0]-0.8}, {S[0]-0.1}, t);")
a = s.index("const CHIPS = ["); b = s.index("];", a) + 2
s = s[:a] + "const CHIPS = [\n  " + ",\n  ".join('{ a: %s + 0.3, b: %s - 0.3, n: "%s", text: "%s", col: "%s" }' % (c[0], c[1], c[2], c[3], c[4]) for c in X["chips"]) + ",\n];" + s[b:]
a = s.index("const ICONS"); b = s.index("};\n", s.index("2: {", a)) + 3
