s = s.replace('"गीज़र ब्लेज़ °C"', f'"{X["fontProbe"]}"')
open(f"{D}/src/{P}/Film.tsx", "w").write(s)
open(f"{D}/src/Root.tsx", "w").write(f'import React from "react";\nimport {{ Composition }} from "remotion";\nimport {{ Film, FILM_FRAMES }} from "./{P}/Film";\nexport const Root: React.FC = () => <Composition id="{comp}" component={{Film}} durationInFrames={{FILM_FRAMES}} fps={{30}} width={{1080}} height={{1920}} />;\n')
