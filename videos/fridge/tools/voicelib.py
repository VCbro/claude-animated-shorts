"""Shared: Hindi narration (offline Piper hi_IN-rohan) with automatic line timing.
LINES = [(gap_before_s, scene, [subtitle chunks])]; a chunk may be "shown|spoken"."""
import json, os, re, wave, io
import numpy as np, soundfile as sf
from scipy.signal import resample_poly
from piper import PiperVoice
from piper.config import SynthesisConfig

SR = 48000
MODEL = os.environ.get("PIPER_MODEL", "/tmp/claude-0/tts/models/vits-piper-hi_IN-rohan-medium/hi_IN-rohan-medium.onnx")

def weight(s):
    letters = len(re.findall(r"[क-हक़-य़अ-औा-ौ0-9a-zA-Z]", s))
    return letters + 3 * len(re.findall(r"[,!?।—]", s))

def build(root, lines, start=0.5, tail=1.2, speed=0.80):
    voice = PiperVoice.load(MODEL)
    cfg = SynthesisConfig(length_scale=speed, noise_scale=0.6, noise_w_scale=0.7)
    clips, meta, t = [], [], start
    for i, (gap, scene, chunks) in enumerate(lines):
        shown = [c.split("|")[0] for c in chunks]; spoken = [c.split("|")[-1] for c in chunks]
        buf = io.BytesIO()
        with wave.open(buf, "wb") as w: voice.synthesize_wav(" ".join(spoken), w, syn_config=cfg)
        buf.seek(0); a, sr = sf.read(buf, dtype="float32"); a = resample_poly(a, SR, sr)
        nz = np.nonzero(np.abs(a) > 0.008)[0]; a = a[max(0, nz[0] - 200): nz[-1] + 2400]
        a = a / (np.max(np.abs(a)) + 1e-9) * 0.8
        if i > 0: t += gap
        dur = len(a) / SR
        w_ = np.array([weight(x) for x in spoken], float)
        edges = np.concatenate([[0], np.cumsum(w_) / w_.sum()]) * (dur - 0.05)
        subs = [{"text": shown[k], "t0": round(t + edges[k], 3), "t1": round(t + edges[k + 1], 3)} for k in range(len(shown))]
        meta.append({"i": i, "scene": scene, "t0": round(t, 3), "t1": round(t + dur, 3), "subs": subs})
        clips.append((t, a)); t += dur
    total = t + tail
    out = np.zeros(int(total * SR) + 10, np.float32)
    for t0, a in clips: s = int(t0 * SR); out[s:s + len(a)] += a
    os.makedirs(f"{root}/voice", exist_ok=True); os.makedirs(f"{root}/src", exist_ok=True)
    sf.write(f"{root}/voice/voice.wav", out, SR, subtype="PCM_24")
    json.dump(meta, open(f"{root}/voice/lines.json", "w"), ensure_ascii=False, indent=1)
    with open(f"{root}/src/lines.ts", "w") as f:
        f.write("// generated by tools/make_voice.py\nexport type Sub = { text: string; t0: number; t1: number };\n"
                "export type Line = { i: number; scene: number; t0: number; t1: number; subs: Sub[] };\n")
        f.write(f"export const VOICE_END = {round(total, 3)};\n")
        f.write("export const LINES: Line[] = " + json.dumps(meta, ensure_ascii=False) + ";\n")
    sc = {}
    for m in meta: sc.setdefault(m["scene"], m["t0"])
    for m in meta: print(f"{m['i']:2d} s{m['scene']} {m['t0']:6.2f}-{m['t1']:6.2f}  {' '.join(s['text'] for s in m['subs'])}")
    print("scene first-line starts:", sc, " total:", round(total, 2))
